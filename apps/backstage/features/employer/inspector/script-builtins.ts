function hasCallParen(sql: string, index: number): boolean {
  let cursor = index;
  while (cursor < sql.length && /\s/.test(sql[cursor] ?? "")) {
    cursor += 1;
  }
  return sql[cursor] === "(";
}

export function isSystemProcedureName(name: string): boolean {
  return SYSTEM_PROCEDURES.has(name.toLowerCase());
}

export function isBuiltinReference(names: readonly string[], sql: string, nextIndex: number): boolean {
  const name = names[names.length - 1]?.toLowerCase() ?? "";
  if (name.length === 0) {
    return false;
  }
  if (names.length === 2) {
    const schema = names[0]?.toLowerCase() ?? "";
    return (schema === "dbo" || schema === "sys") && SYSTEM_PROCEDURES.has(name);
  }
  if (names.length !== 1) {
    return false;
  }
  if (SYSTEM_PROCEDURES.has(name) || NILADIC.has(name)) {
    return true;
  }
  return FUNCTIONS.has(name) && hasCallParen(sql, nextIndex);
}
